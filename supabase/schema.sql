create table if not exists public.budgets (
  month text primary key check (month ~ '^\d{4}-\d{2}$'),
  amount_cents integer not null check (amount_cents >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  amount_cents integer not null check (amount_cents > 0),
  category text not null references public.categories(name) on update cascade,
  description text not null check (char_length(description) <= 140),
  paid_by text not null references public.app_users(id),
  created_by text not null references public.app_users(id),
  expense_date date not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists expenses_month_idx on public.expenses ((to_char(expense_date, 'YYYY-MM')));
create index if not exists expenses_created_by_idx on public.expenses (created_by, created_at desc);

alter table public.app_users enable row level security;
alter table public.categories enable row level security;
alter table public.budgets enable row level security;
alter table public.expenses enable row level security;

create or replace function public.restore_home_budget(payload jsonb)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  category_item text;
  budget_item jsonb;
  expense_item jsonb;
begin
  if jsonb_typeof(payload -> 'categories') <> 'array'
    or jsonb_typeof(payload -> 'budgets') <> 'array'
    or jsonb_typeof(payload -> 'expenses') <> 'array' then
    raise exception 'Invalid backup payload';
  end if;

  delete from public.expenses;
  delete from public.budgets;
  delete from public.categories;

  insert into public.app_users (id, display_name)
  values ('ido', 'עידו'), ('karina', 'קארינה')
  on conflict (id) do update set display_name = excluded.display_name;

  for category_item in select jsonb_array_elements_text(payload -> 'categories')
  loop
    insert into public.categories (name) values (category_item);
  end loop;

  for budget_item in select jsonb_array_elements(payload -> 'budgets')
  loop
    insert into public.budgets (month, amount_cents, created_at, updated_at)
    values (
      budget_item ->> 'month',
      (budget_item ->> 'amountCents')::integer,
      coalesce((budget_item ->> 'createdAt')::timestamptz, now()),
      coalesce((budget_item ->> 'updatedAt')::timestamptz, now())
    );
  end loop;

  for expense_item in select jsonb_array_elements(payload -> 'expenses')
  loop
    insert into public.expenses (
      id,
      amount_cents,
      category,
      description,
      paid_by,
      created_by,
      expense_date,
      created_at,
      updated_at
    )
    values (
      nullif(expense_item ->> 'id', '')::bigint,
      (expense_item ->> 'amountCents')::integer,
      expense_item ->> 'category',
      expense_item ->> 'description',
      expense_item ->> 'paidBy',
      expense_item ->> 'createdBy',
      (expense_item ->> 'expenseDate')::date,
      coalesce((expense_item ->> 'createdAt')::timestamptz, now()),
      coalesce((expense_item ->> 'updatedAt')::timestamptz, now())
    );
  end loop;

  perform setval(
    pg_get_serial_sequence('public.expenses', 'id'),
    coalesce((select max(id) from public.expenses), 1),
    (select count(*) > 0 from public.expenses)
  );
end;
$$;
